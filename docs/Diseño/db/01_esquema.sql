--TABLA USUARIOS
CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    correo VARCHAR(150) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    rol VARCHAR(20)  NOT NULL,
    activo BOOLEAN      NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT uq_usuarios_correo UNIQUE (correo),
    CONSTRAINT ck_usuarios_rol    CHECK (rol IN ('ESTUDIANTE', 'DOCENTE', 'ADMIN'))
);

--TABLA CURSOS
CREATE TABLE cursos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    descripcion TEXT,
    docente_id BIGINT NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMP    NOT NULL DEFAULT now(),
    -- RN-08: la BD garantiza que el docente exista; que tenga rol DOCENTE lo valida el servidor
    CONSTRAINT fk_cursos_docente FOREIGN KEY (docente_id) REFERENCES usuarios (id)
);

--TABLA MATRICULAS
CREATE TABLE matriculas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id BIGINT NOT NULL,
    curso_id BIGINT NOT NULL,
    fecha_matricula TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT fk_matriculas_estudiante FOREIGN KEY (estudiante_id) REFERENCES usuarios (id),
    CONSTRAINT fk_matriculas_curso      FOREIGN KEY (curso_id)      REFERENCES cursos (id),
    CONSTRAINT uq_matriculas_estudiante_curso UNIQUE (estudiante_id, curso_id)
);
 
CREATE TABLE temas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    curso_id BIGINT       NOT NULL,
    nombre VARCHAR(120) NOT NULL,
    orden INT          NOT NULL DEFAULT 1,
    activo BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_temas_curso FOREIGN KEY (curso_id) REFERENCES cursos (id)
);

--Preguntas
 
CREATE TABLE preguntas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tema_id  BIGINT NOT NULL,
    enunciado TEXT NOT NULL,
    dificultad SMALLINT NOT NULL,
    tipo VARCHAR(25) NOT NULL,
    retroalimentacion TEXT,
    activa BOOLEAN     NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT fk_preguntas_tema FOREIGN KEY (tema_id) REFERENCES temas (id),
    CONSTRAINT ck_preguntas_dificultad CHECK (dificultad BETWEEN 1 AND 3),
    CONSTRAINT ck_preguntas_tipo CHECK (tipo IN ('SELECCION_MULTIPLE', 'VERDADERO_FALSO'))
);
 
CREATE TABLE opciones_pregunta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pregunta_id BIGINT NOT NULL,
    texto VARCHAR(500) NOT NULL,
    es_correcta BOOLEAN NOT NULL DEFAULT FALSE,
    orden INT NOT NULL DEFAULT 1,
    CONSTRAINT fk_opciones_pregunta FOREIGN KEY (pregunta_id) REFERENCES preguntas (id),
    -- Necesario para la llave foránea compuesta de respuestas (ver más abajo)
    CONSTRAINT uq_opciones_id_pregunta UNIQUE (id, pregunta_id)
);

-- TABLA EVALUACIONES
CREATE TABLE evaluaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    curso_id BIGINT NOT NULL,
    nombre VARCHAR(150) NOT NULL,
    tipo VARCHAR(20) NOT NULL DEFAULT 'FORMATIVA',
    intentos_permitidos INT,
    activa BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT fk_evaluaciones_curso FOREIGN KEY (curso_id) REFERENCES cursos (id),
    CONSTRAINT ck_evaluaciones_tipo  CHECK (tipo IN ('INICIAL', 'FORMATIVA', 'CONFIRMACION')),
    CONSTRAINT ck_evaluaciones_intentos CHECK (intentos_permitidos IS NULL OR intentos_permitidos > 0)
);
 
CREATE TABLE evaluacion_preguntas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluacion_id BIGINT NOT NULL,
    pregunta_id BIGINT NOT NULL,
    orden INT    NOT NULL DEFAULT 1,
    CONSTRAINT fk_evpreg_evaluacion FOREIGN KEY (evaluacion_id) REFERENCES evaluaciones (id),
    CONSTRAINT fk_evpreg_pregunta   FOREIGN KEY (pregunta_id)   REFERENCES preguntas (id),
    CONSTRAINT uq_evpreg_evaluacion_pregunta UNIQUE (evaluacion_id, pregunta_id)
);

--TABLA INTENTOS
 
CREATE TABLE intentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id BIGINT      NOT NULL,
    evaluacion_id BIGINT,                           -- solo si tipo = EVALUACION
    tema_id BIGINT,                           -- solo si tipo = PRACTICA
    tipo VARCHAR(15) NOT NULL,
    estado VARCHAR(15) NOT NULL DEFAULT 'EN_CURSO',
    fecha_inicio TIMESTAMP   NOT NULL DEFAULT now(),
    fecha_fin TIMESTAMP,
    puntuacion NUMERIC(5,2),
    CONSTRAINT fk_intentos_estudiante FOREIGN KEY (estudiante_id) REFERENCES usuarios (id),
    CONSTRAINT fk_intentos_evaluacion FOREIGN KEY (evaluacion_id) REFERENCES evaluaciones (id),
    CONSTRAINT fk_intentos_tema       FOREIGN KEY (tema_id)       REFERENCES temas (id),
    CONSTRAINT ck_intentos_tipo       CHECK (tipo   IN ('EVALUACION', 'PRACTICA')),
    CONSTRAINT ck_intentos_estado     CHECK (estado IN ('EN_CURSO', 'FINALIZADO')),
    CONSTRAINT ck_intentos_puntuacion CHECK (puntuacion IS NULL OR puntuacion BETWEEN 0 AND 100),
    -- RN-16: evaluación (con evaluacion_id) o práctica (con tema_id), nunca ambos ni ninguno
    CONSTRAINT ck_intentos_tipo_coherente CHECK (
           (tipo = 'EVALUACION' AND evaluacion_id IS NOT NULL AND tema_id IS NULL)
        OR (tipo = 'PRACTICA'   AND tema_id IS NOT NULL AND evaluacion_id IS NULL)
    ),
    -- RN-19: un intento FINALIZADO siempre tiene puntuación y fecha de fin
    CONSTRAINT ck_intentos_finalizado CHECK (
        estado = 'EN_CURSO' OR (puntuacion IS NOT NULL AND fecha_fin IS NOT NULL)
    )
);

--TABLA RESPUESTAS
 
CREATE TABLE respuestas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    intento_id BIGINT NOT NULL,
    pregunta_id BIGINT NOT NULL,
    opcion_id BIGINT,
    es_correcta BOOLEAN,
    CONSTRAINT fk_respuestas_intento  FOREIGN KEY (intento_id)  REFERENCES intentos (id),
    CONSTRAINT fk_respuestas_pregunta FOREIGN KEY (pregunta_id) REFERENCES preguntas (id),
    -- Llave foránea COMPUESTA: la opción elegida debe pertenecer a la misma pregunta.
    -- Si opcion_id es NULL (sin responder), PostgreSQL no valida esta restricción.
    CONSTRAINT fk_respuestas_opcion_de_pregunta
        FOREIGN KEY (opcion_id, pregunta_id) REFERENCES opciones_pregunta (id, pregunta_id),
    CONSTRAINT uq_respuestas_intento_pregunta UNIQUE (intento_id, pregunta_id)-- una respuesta por pregunta
);
 
--TABLA PROGRESO_TEMA

CREATE TABLE progreso_tema (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id BIGINT NOT NULL,
    tema_id BIGINT NOT NULL,
    total_respuestas INT NOT NULL DEFAULT 0,
    respuestas_correctas INT NOT NULL DEFAULT 0,
    porcentaje_aciertos NUMERIC(5,2) NOT NULL DEFAULT 0,
    intentos_satisfactorios INT NOT NULL DEFAULT 0,
    nivel VARCHAR(15)   NOT NULL DEFAULT 'SIN_DATOS',
    fecha_actualizacion TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT fk_progreso_estudiante FOREIGN KEY (estudiante_id) REFERENCES usuarios (id),
    CONSTRAINT fk_progreso_tema FOREIGN KEY (tema_id) REFERENCES temas (id),
    CONSTRAINT uq_progreso_estudiante_tema UNIQUE (estudiante_id, tema_id),           -- un solo resumen por estudiante y tema
    CONSTRAINT ck_progreso_totales CHECK (respuestas_correctas >= 0 AND respuestas_correctas <= total_respuestas),
    CONSTRAINT ck_progreso_porcentaje CHECK (porcentaje_aciertos BETWEEN 0 AND 100),
    CONSTRAINT ck_progreso_intentos CHECK (intentos_satisfactorios >= 0),
    CONSTRAINT ck_progreso_nivel CHECK (nivel IN ('SIN_DATOS', 'REFUERZO', 'INTERMEDIO', 'AVANZADO', 'DOMINADO'))
);

--TABLA RECOMENDACIONES

CREATE TABLE recomendaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id BIGINT NOT NULL,
    tema_id BIGINT NOT NULL,
    tipo_actividad VARCHAR(30) NOT NULL,
    motivo TEXT NOT NULL,            -- RN-26: toda recomendación explica su motivo
    vigente BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT fk_recomendaciones_estudiante FOREIGN KEY (estudiante_id) REFERENCES usuarios (id),
    CONSTRAINT fk_recomendaciones_tema FOREIGN KEY (tema_id)       REFERENCES temas (id),
    CONSTRAINT ck_recomendaciones_tipo CHECK (tipo_actividad IN ('REFUERZO', 'PRACTICA_ADICIONAL', 'AVANZADO', 'CONFIRMACION'))
);
 
-- RN-26: solo una recomendación vigente por estudiante y tema (índice único PARCIAL:
-- solo cuenta las filas con vigente = true). Para crear una nueva, primero se pone
-- vigente = false a la anterior y luego se inserta la nueva.

CREATE UNIQUE INDEX uq_recomendacion_vigente
    ON recomendaciones (estudiante_id, tema_id)
    WHERE vigente;

--TABLA AUDITORIA
 
CREATE TABLE auditoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT, --puede ser null en caso de que el trigger noc onzca el user
    accion VARCHAR(30) NOT NULL,
    entidad VARCHAR(60) NOT NULL,
    entidad_id BIGINT,
    detalle TEXT,
    fecha TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT fk_auditoria_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
);

--TABLA CONFIGURACION

CREATE TABLE configuracion (
    clave VARCHAR(60) PRIMARY KEY,
    valor VARCHAR(200) NOT NULL,
    descripcion VARCHAR(255)
);
 
 
